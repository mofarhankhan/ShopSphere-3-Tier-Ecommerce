import { Router } from 'express';
import { asyncHandler } from '../utils/http.js';
import { protect, adminOnly } from '../middleware/auth.js';
import * as auth from '../controllers/auth.js';
import * as products from '../controllers/products.js';
import * as cart from '../controllers/cart.js';
import * as orders from '../controllers/orders.js';
import * as admin from '../controllers/admin.js';

const router = Router();
router.get('/health', (req, res) => res.json({ status: 'ok', service: 'shopsphere-api' }));
router.post('/auth/register', asyncHandler(auth.register));
router.post('/auth/login', asyncHandler(auth.login));
router.get('/auth/me', protect, asyncHandler(auth.me));
router.get('/products', asyncHandler(products.listProducts));
router.get('/products/:id', asyncHandler(products.getProduct));
router.get('/categories', asyncHandler(products.listCategories));
router.get('/cart', protect, asyncHandler(cart.getCart));
router.post('/cart/items', protect, asyncHandler(cart.addItem));
router.patch('/cart/items/:id', protect, asyncHandler(cart.updateItem));
router.delete('/cart/items/:id', protect, asyncHandler(cart.removeItem));
router.post('/orders', protect, asyncHandler(orders.createOrder));
router.get('/orders/my', protect, asyncHandler(orders.myOrders));
router.get('/orders/:id', protect, asyncHandler(orders.getOrder));
router.get('/admin/stats', protect, adminOnly, asyncHandler(admin.stats));
router.post('/admin/products', protect, adminOnly, asyncHandler(admin.createProduct));
router.patch('/admin/products/:id', protect, adminOnly, asyncHandler(admin.updateProduct));
router.delete('/admin/products/:id', protect, adminOnly, asyncHandler(admin.deleteProduct));
router.get('/admin/orders', protect, adminOnly, asyncHandler(orders.adminOrders));
router.patch('/admin/orders/:id/status', protect, adminOnly, asyncHandler(orders.updateOrderStatus));
export default router;
